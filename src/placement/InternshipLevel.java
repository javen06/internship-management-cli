package placement;

/**
 * Represents the difficulty level or target year for an internship.
 * This is used to filter internships based on a student's year of study.
 *
 * @version 1.0
 */
public enum InternshipLevel {
    /**
     * For Year 1 and 2 students.
     */
    BASIC,

    /**
     * For Year 3 and above students.
     */
    INTERMEDIATE,

    /**
     * For Year 3 and above students.
     */
    ADVANCED
}